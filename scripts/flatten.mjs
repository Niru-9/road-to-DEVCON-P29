#!/usr/bin/env node
/**
 * Dependency-free Solidity flattener for the Remix single-file workflow.
 *
 * Foundry's `forge flatten` is preferred when available; this script exists so
 * the contract can be flattened with only the npm dependencies installed:
 *
 *   node scripts/flatten.mjs \
 *     contracts/src/QuadraticFundingRound.sol \
 *     contracts/remix/QuadraticFundingRound.sol
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const [, , entryArg, outputArg] = process.argv;

if (!entryArg || !outputArg) {
  console.error('usage: node scripts/flatten.mjs <entry.sol> <output.sol>');
  process.exit(1);
}

const root = process.cwd();
const entry = resolve(root, entryArg);
const output = resolve(root, outputArg);
const visited = new Set();
const files = [];

const IMPORT_RE = /^\s*import\s+(?:(?:\{[^}]*\}|\*\s+as\s+\w+)\s+from\s+)?["']([^"']+)["']\s*;\s*$/gm;

function resolveImport(specifier, fromFile) {
  if (specifier.startsWith('@openzeppelin/contracts/')) {
    return resolve(root, 'node_modules', specifier);
  }
  if (specifier.startsWith('forge-std/')) {
    return resolve(root, 'node_modules', specifier);
  }
  if (specifier.startsWith('.')) {
    return resolve(dirname(fromFile), specifier);
  }
  throw new Error(`Unsupported import "${specifier}" in ${fromFile}`);
}

function visit(file) {
  const absolute = resolve(file);
  if (visited.has(absolute)) return;
  visited.add(absolute);

  const source = readFileSync(absolute, 'utf8');
  const imports = [...source.matchAll(IMPORT_RE)].map((match) => match[1]);

  for (const specifier of imports) {
    visit(resolveImport(specifier, absolute));
  }

  files.push({ path: absolute, source: source.replace(IMPORT_RE, '').trim() });
}

visit(entry);

const body = files
  .map(({ path, source }) => {
    const relative = path.startsWith(root) ? path.slice(root.length + 1) : path;
    // Keep one SPDX header per dependency block for auditability, but drop the
    // duplicate pragma lines that would otherwise repeat dozens of times.
    const cleaned = source
      .replace(/^\s*\/\/ SPDX-License-Identifier:.*$/gm, '')
      .replace(/^\s*pragma solidity[^;]+;\s*$/gm, '')
      .trim();
    return `// ---- ${relative.replace(/\\/g, '/')} ----\n\n${cleaned}`;
  })
  .join('\n\n');

const header = `// SPDX-License-Identifier: MIT
// Flattened for Remix deployment. Generated by scripts/flatten.mjs.
// Source entrypoint: ${entryArg}
pragma solidity 0.8.24;

`;

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, `${header}${body}\n`, 'utf8');
console.log(`Flattened ${files.length} files -> ${outputArg}`);
